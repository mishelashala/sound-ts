/**
 * Bundle @mishelashala/superset-ts-core `transform` plus the playground UI
 * into docs/playground.js. GitHub Pages only serves docs/ and does not build.
 *
 * esbuild is the copy already installed via vite (pnpm). TypeScript's
 * transpileModule is not bundled; the page loads a pinned CDN build.
 */
import { readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pnpmDir = join(root, "node_modules/.pnpm");
const esbuildDir = readdirSync(pnpmDir).find((name) => name.startsWith("esbuild@"));
if (!esbuildDir) {
  console.error("esbuild is missing. Run pnpm install (vite depends on esbuild).");
  process.exit(1);
}

const esbuildPath = join(pnpmDir, esbuildDir, "node_modules/esbuild/lib/main.js");
const esbuild = await import(pathToFileURL(esbuildPath).href);

await esbuild.build({
  absWorkingDir: root,
  entryPoints: ["scripts/playground/main.js"],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2020",
  outfile: "docs/playground.js",
  legalComments: "none",
  // emitMethods imports `typescript`; the page already loads a CDN build.
  alias: {
    typescript: join(root, "scripts/playground/typescript-cdn-shim.js"),
  },
  banner: {
    js: "/* Generated by scripts/build-playground.mjs — rebuild after core or playground UI edits. */",
  },
});
